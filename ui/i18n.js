const COCONUT_LANGS = ['zh-Hans', 'zh-Hant', 'ja', 'ko', 'en'];

/** 把系统语言标签映射成我们支持的 5 种之一。 */
function resolveLocale(tags) {
  const list = (Array.isArray(tags) ? tags : [tags]).filter(Boolean).map((tag) => String(tag).toLowerCase());
  for (const tag of list) {
    if (tag.startsWith('zh')) {
      const traditional =
        tag.includes('hant') ||
        /-(tw|hk|mo)\b/.test(tag) ||
        tag === 'zh-tw' ||
        tag === 'zh-hk' ||
        tag === 'zh-mo';
      // zh / zh-hans* 以及 zh-sg 都按简体处理（旧的 zh-CN 也认）
      return traditional ? 'zh-Hant' : 'zh-Hans';
    }
    if (tag.startsWith('ja')) return 'ja';
    if (tag.startsWith('ko')) return 'ko';
    if (tag.startsWith('en')) return 'en';
    // 其它语言继续往后找，找不到就落到英文
  }
  return 'en';
}

function detectLocale() {
  const nav = typeof navigator === 'undefined' ? {} : navigator;
  const tags = nav.languages && nav.languages.length ? nav.languages : [nav.language];
  return resolveLocale(tags);
}

let coconutLocale = detectLocale();

function coconutTranslate(key, vars) {
  const table = COCONUT_DICT[coconutLocale] || COCONUT_DICT.en;
  let text = table[key];
  if (text === undefined) text = COCONUT_DICT.en[key];
  if (text === undefined) return key;
  if (vars) {
    return String(text).replace(/\{(\w+)\}/g, (match, name) =>
      vars[name] === undefined ? match : String(vars[name]),
    );
  }
  return String(text);
}

/** 填 data-i18n 系列属性（静态文本 / title / aria-label / placeholder）。 */
function applyStaticI18n(root) {
  const scope = root || document;
  for (const node of scope.querySelectorAll('[data-i18n]')) {
    node.textContent = coconutTranslate(node.dataset.i18n);
  }
  for (const node of scope.querySelectorAll('[data-i18n-title]')) {
    const text = coconutTranslate(node.dataset.i18nTitle);
    node.title = text;
    node.setAttribute('aria-label', text);
  }
  for (const node of scope.querySelectorAll('[data-i18n-placeholder]')) {
    node.placeholder = coconutTranslate(node.dataset.i18nPlaceholder);
  }
}

function applyDocumentLocale() {
  document.documentElement.lang = coconutLocale;
  document.title = coconutTranslate('app.title');
}

